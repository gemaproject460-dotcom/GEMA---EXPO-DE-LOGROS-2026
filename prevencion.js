// FUNCIÓN PARA CAMBIAR IDIOMA
// ==========================================
function cambiarIdioma(idioma) {
    localStorage.setItem("idioma", idioma);

    document.querySelectorAll("[data-i18n]").forEach(elemento => {
        const key = elemento.getAttribute("data-i18n");
        if (translations[idioma][key]) {
            elemento.innerHTML = translations[idioma][key];
        }
    });
}

// ==========================================
// DESPLAZAMIENTO SUAVE AL HACER CLIC EN BOTONES
// ==========================================
document.addEventListener("DOMContentLoaded", function() {
    
    // --- 1. DESPLAZAMIENTO SUAVE A SECCIONES ---
    const buttons = document.querySelectorAll(".btn-natural");
    
    buttons.forEach(button => {
        button.addEventListener("click", function(e) {
            e.preventDefault();
            
            // Obtener el href del botón
            const targetId = this.getAttribute("href");
            
            if (targetId && targetId.startsWith("#")) {
                const targetElement = document.querySelector(targetId);
                
                if (targetElement) {
                    // Calcular posición con offset para mejor visualización
                    const headerOffset = 80;
                    const elementPosition = targetElement.getBoundingClientRect().top;
                    const offsetPosition = elementPosition + window.pageYOffset - headerOffset;
                    
                    // Desplazamiento suave
                    window.scrollTo({
                        top: offsetPosition,
                        behavior: "smooth"
                    });
                    
                    // Efecto de resalte en la sección destino
                    targetElement.style.transition = "background-color 0.6s ease";
                    targetElement.style.backgroundColor = "rgba(10, 92, 168, 0.08)";
                    
                    setTimeout(() => {
                        targetElement.style.backgroundColor = "transparent";
                    }, 1500);
                }
            }
        });
    });

    // --- 2. EFECTO HOVER EN BOTONES ---
    const allButtons = document.querySelectorAll(".btn-natural");
    allButtons.forEach(btn => {
        btn.addEventListener("mouseenter", function() {
            this.style.transform = "scale(1.05)";
            this.style.boxShadow = "0 8px 20px rgba(10, 92, 168, 0.3)";
            this.style.transition = "transform 0.3s ease, box-shadow 0.3s ease";
        });
        btn.addEventListener("mouseleave", function() {
            this.style.transform = "scale(1)";
            this.style.boxShadow = "none";
        });
    });

    // --- 3. ANIMACIÓN DE ICONOS EN CARDS ---
    const icons = document.querySelectorAll(".icono i");
    
    icons.forEach((icon) => {
        const iconParent = icon.closest(".natural-card");
        if (iconParent) {
            iconParent.addEventListener("mouseenter", () => {
                icon.style.transition = "transform 0.5s ease";
                icon.style.transform = "scale(1.2) rotate(5deg)";
            });
            iconParent.addEventListener("mouseleave", () => {
                icon.style.transition = "transform 0.5s ease";
                icon.style.transform = "scale(1) rotate(0deg)";
            });
        }
    });

    // --- 4. EFECTO DE RESALTE EN LINKS DEL NAVBAR ---
    const navLinks = document.querySelectorAll(".navbar a:not(.dropbtn)");
    navLinks.forEach(link => {
        link.addEventListener("click", function() {
            // Remover clase active de todos
            navLinks.forEach(l => l.classList.remove("active"));
            // Añadir clase active al clickeado
            this.classList.add("active");
        });
    });
});

